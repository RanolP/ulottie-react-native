/// Same whitelist as skia-aot: the rt rasterizer draws the same display list.
fn supported() -> Caps {
    rn::supported() | Caps::GRADIENT | Caps::RAMP | Caps::FX
}

/// Past this many display-list nodes, tiny-skia at 512² cannot hold 60 fps on
/// a phone (measured in the Phase-0 spike; ~2000 nodes is infeasible). The
/// scene still compiles — budget is a warning, correctness is a refusal.
const NODE_BUDGET: usize = 500;

pub fn report(module: &ir::Module, _options: &CompileOptions) -> Result<Option<Report>> {
    if !data::can_encode(module) {
        return Ok(None);
    }
    ensure!(
        module.expressions.is_empty(),
        "the rt target does not support expressions"
    );
    let payload = data::encode(module)?;
    // Integer-frame bake grid: eases are folded into the per-frame samples,
    // and the native player lerps between neighbouring integers.
    let frames: Vec<f64> = {
        let lo = payload.c.ip.ceil() as i64;
        let hi = payload.c.op.floor() as i64;
        (lo..=hi).map(|f| f as f64).collect()
    };
    let (scene, samples) = scene::plan_sampled(&payload, &[], &frames)?;
    let missing = scene.caps - supported();
    ensure!(
        missing.is_empty(),
        "the rt target does not support: {}",
        emit::caps_list(missing)
    );

    let (mut anim, elements) = animation_from_markup(&scene)?;
    anim.tracks = build_tracks(&samples, &frames)?;
    stamp_bboxes(&mut anim, &frames);

    let node_count = anim.nodes.len();
    let warning = (node_count > NODE_BUDGET).then(|| {
        format!(
            "WARNING: {node_count} display-list nodes exceed the rt target's ~{NODE_BUDGET}-node \
             60 fps budget (tiny-skia @512²); expect dropped frames on device"
        )
    });
    if let Some(w) = &warning {
        eprintln!("{w}");
    }

    let blob = rtdl::encode(&anim).context("RTDL encode")?;
    let b64 = base64::engine::general_purpose::STANDARD.encode(&blob);

    let n = |v: f64| crate::scene::svg::n(v);
    let meta = format!(
        "{{ fr: {}, ip: {}, op: {}, width: {}, height: {} }}",
        n(scene.data.fr),
        n(scene.data.ip),
        n(scene.data.op),
        n(anim.width as f64),
        n(anim.height as f64),
    );
    let mut js = format!(
        "// Generated by ulottie — rt target (native tiny-skia rasterizer via ulottie-rt).\n\
         // The scene ships as RTDL: a binary display list + numeric keyframe tracks,\n\
         // decoded and played natively; per-frame JS work is one renderFrame() call.\n\
         // caps: {}\n",
        emit::caps_list(scene.caps),
    );
    if let Some(w) = &warning {
        js.push_str(&format!("// {w}\n"));
    }
    js.push_str(&format!(
        "\nexport const rtdl = '{b64}';\n\nexport const meta = {meta};\n\n\
         export const init = () => ({meta});\n"
    ));

    let mut caps: Vec<String> = scene
        .caps
        .iter_names()
        .map(|(n, _)| n.to_string())
        .collect();
    caps.sort_unstable();
    Ok(Some(Report {
        js,
        caps,
        modules: Vec::new(),
        runtime_slice: 0,
        is_static: scene.is_static(),
        instanced: false,
        templated: false,
        elements,
        bindings: scene.data.b.len(),
        records: 0,
        generated: false,
        instance_clocks: false,
        assets: Vec::new(),
    }))
}

