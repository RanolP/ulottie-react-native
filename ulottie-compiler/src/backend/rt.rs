// Numeric parsers — the compiler's own baked output grammar, parsed back.
// ---------------------------------------------------------------------------

fn fnum(v: &str, what: &str) -> Result<f32> {
    v.parse::<f64>()
        .map(|f| f as f32)
        .map_err(|_| anyhow::anyhow!("non-numeric `{what}` value `{v}` in the rt target"))
}

/// The two transform spellings the compiler writes (see `scene::svg`), as
/// SVG-order `[a, b, c, d, e, f]`.
fn transform6(v: &str) -> Result<[f32; 6]> {
    if let Some(args) = v.strip_prefix("matrix(").and_then(|r| r.strip_suffix(')')) {
        let p: Vec<&str> = args.split(',').collect();
        ensure!(p.len() == 6, "matrix() with {} arguments", p.len());
        let mut m = [0.0f32; 6];
        for (i, s) in p.iter().enumerate() {
            m[i] = fnum(s, "matrix")?;
        }
        Ok(m)
    } else if let Some(args) = v
        .strip_prefix("translate(")
        .and_then(|r| r.strip_suffix(')'))
    {
        let p: Vec<&str> = args.split(',').collect();
        ensure!(p.len() == 2, "translate() with {} arguments", p.len());
        Ok([
            1.0,
            0.0,
            0.0,
            1.0,
            fnum(p[0], "translate")?,
            fnum(p[1], "translate")?,
        ])
    } else {
        bail!("unsupported transform `{v}` in the rt target")
    }
}

/// `#rgb` / `#rrggbb` / `rgb(r,g,b)` / `rgba(r,g,b,a)` → straight RGBA 0..=1.
fn color4(v: &str) -> Result<[f32; 4]> {
    if let Some(hex) = v.strip_prefix('#') {
        let d = |c: u8| -> Result<u32> {
            (c as char)
                .to_digit(16)
                .ok_or_else(|| anyhow::anyhow!("bad hex colour `{v}`"))
        };
        let b = hex.as_bytes();
        let (r, g, bl) = match b.len() {
            3 => (d(b[0])? * 17, d(b[1])? * 17, d(b[2])? * 17),
            6 => (
                d(b[0])? * 16 + d(b[1])?,
                d(b[2])? * 16 + d(b[3])?,
                d(b[4])? * 16 + d(b[5])?,
            ),
            _ => bail!("bad hex colour `{v}`"),
        };
        return Ok([r as f32 / 255.0, g as f32 / 255.0, bl as f32 / 255.0, 1.0]);
    }
    let (body, has_alpha) = if let Some(r) = v.strip_prefix("rgba(") {
        (r, true)
    } else if let Some(r) = v.strip_prefix("rgb(") {
        (r, false)
    } else {
        bail!("unsupported colour `{v}` in the rt target")
    };
    let body = body
        .strip_suffix(')')
        .ok_or_else(|| anyhow::anyhow!("unterminated colour `{v}`"))?;
    let p: Vec<&str> = body.split(',').map(str::trim).collect();
    ensure!(p.len() == if has_alpha { 4 } else { 3 }, "bad colour `{v}`");
    let ch = |s: &str| -> Result<f32> { Ok(fnum(s, "colour")? / 255.0) };
    Ok([
        ch(p[0])?,
        ch(p[1])?,
        ch(p[2])?,
        if has_alpha { fnum(p[3], "alpha")? } else { 1.0 },
    ])
}

/// The compiler's own `d` grammar (`scene::svg::FlatPath::to_d`): absolute
/// `M`/`L`/`C`/`Z` only, numbers quantized, comma elided before negatives.
fn parse_path(d: &str) -> Result<PathData> {
    let mut out = PathData::default();
    let b = d.as_bytes();
    let mut i = 0usize;
    let read_num = |i: &mut usize| -> Result<f32> {
        while *i < b.len() && matches!(b[*i], b' ' | b',') {
            *i += 1;
        }
        let start = *i;
        if *i < b.len() && matches!(b[*i], b'-' | b'+') {
            *i += 1;
        }
        while *i < b.len() && matches!(b[*i], b'0'..=b'9' | b'.') {
            *i += 1;
        }
        ensure!(*i > start, "expected a number at byte {start} of `d`");
        fnum(&d[start..*i], "d")
    };
    while i < b.len() {
        match b[i] {
            b' ' | b',' => i += 1,
            b'M' | b'L' => {
                let verb = if b[i] == b'M' { VERB_MOVE } else { VERB_LINE };
                i += 1;
                out.verbs.push(verb);
                out.points.push(read_num(&mut i)?);
                out.points.push(read_num(&mut i)?);
            }
            b'C' => {
                i += 1;
                out.verbs.push(VERB_CUBIC);
                for _ in 0..6 {
                    out.points.push(read_num(&mut i)?);
                }
            }
            b'Z' => {
                i += 1;
                out.verbs.push(VERB_CLOSE);
            }
            other => bail!(
                "unsupported path command `{}` in the rt target",
                other as char
            ),
        }
    }
    Ok(out)
}

fn blend_of(kw: &str) -> Result<Blend> {
    Ok(match kw {
        "multiply" => Blend::Multiply,
        "screen" => Blend::Screen,
        "overlay" => Blend::Overlay,
        "darken" => Blend::Darken,
        "lighten" => Blend::Lighten,
        "color-dodge" => Blend::ColorDodge,
        "color-burn" => Blend::ColorBurn,
        "hard-light" => Blend::HardLight,
        "soft-light" => Blend::SoftLight,
        "difference" => Blend::Difference,
        "exclusion" => Blend::Exclusion,
        "hue" => Blend::Hue,
        "saturation" => Blend::Saturation,
        "color" => Blend::Color,
        "luminosity" => Blend::Luminosity,
        other => bail!("unsupported mix-blend-mode `{other}`"),
    })
}

fn fill_rule_eo(v: &str) -> Result<bool> {
    match v {
        "evenodd" => Ok(true),
        "nonzero" => Ok(false),
        other => bail!("unsupported fill rule `{other}`"),
    }
}

