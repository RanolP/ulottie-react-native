/// One channel's parsed per-frame value, comparable for change-point
/// compression.
#[derive(Clone, Debug, PartialEq)]
enum Val {
    F(f32),
    F2([f32; 2]),
    F4([f32; 4]),
    F6([f32; 6]),
    Path(PathData),
    Dash(Dash),
}

/// Channel discriminants, ordered so tracks emit deterministically.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
enum Kind {
    Matrix,
    Opacity,
    Hidden,
    Path,
    Rect,
    Ellipse,
    Fill,
    FillOpacity,
    Stroke,
    StrokeOpacity,
    StrokeWidth,
    Dash,
    Gradient,
    Stop,
    BlurStd,
    ShadowStd,
    FloodOpacity,
    ShadowOffset,
}

/// One live binding sample → its channel writes. The op code disambiguates
/// where attribute names alone cannot (`style:display:none` hides an element
/// under DISPLAY but empties its path under a trimmed SHAPE; `stdDeviation`
/// is an x/y pair under FX_BLUR and a scalar under FX_STD).
fn channel_writes(opc: u8, attrs: &[(String, String)]) -> Result<Vec<(Kind, Val)>> {
    let get = |k: &str| attrs.iter().find(|(a, _)| a == k).map(|(_, v)| v.as_str());
    let hidden = attrs
        .iter()
        .any(|(k, v)| k == "style" && v == "display:none");
    let mut out = Vec::new();
    match opc {
        op::TRANSFORM | op::TRANSLATE | op::TRANSFORM_SKEW | op::LAYER_TX => {
            if let Some(v) = get("transform") {
                out.push((Kind::Matrix, Val::F6(transform6(v)?)));
            }
        }
        op::OPACITY | op::LAYER_OP => {
            if let Some(v) = get("opacity") {
                out.push((Kind::Opacity, Val::F(fnum(v, "opacity")?)));
            }
        }
        op::DISPLAY => {
            // A live DISPLAY write is the value even when it writes nothing:
            // the runtime clears the attribute on a visible frame.
            out.push((Kind::Hidden, Val::F(if hidden { 1.0 } else { 0.0 })));
        }
        op::SHAPE | op::SHAPE_RECT | op::SHAPE_ELLIPSE | op::SHAPE_STAR | op::SHAPE_MULTI => {
            // A SHAPE write is authoritative for visibility: a trim that
            // empties hides the element (the skia runtime sets `hd` from the
            // frame's attrs), and a `d` write shows it — the static markup may
            // carry `display:none` when the shape is empty at frame `ip`.
            out.push((Kind::Hidden, Val::F(if hidden { 1.0 } else { 0.0 })));
            if let Some(d) = get("d")
                && !hidden
            {
                out.push((Kind::Path, Val::Path(parse_path(d)?)));
            }
        }
        op::RECT => {
            let f = |k: &str, def: f32| -> Result<f32> {
                get(k)
                    .map(|v| fnum(v, k))
                    .transpose()
                    .map(|o| o.unwrap_or(def))
            };
            out.push((
                Kind::Rect,
                Val::F6([
                    f("x", 0.0)?,
                    f("y", 0.0)?,
                    f("width", 0.0)?,
                    f("height", 0.0)?,
                    f("rx", 0.0)?,
                    f("ry", 0.0)?,
                ]),
            ));
        }
        op::ELLIPSE => {
            let f = |k: &str| -> Result<f32> { fnum(get(k).unwrap_or("0"), k) };
            out.push((
                Kind::Ellipse,
                Val::F4([f("cx")?, f("cy")?, f("rx")?, f("ry")?]),
            ));
        }
        op::FILL => {
            if let Some(v) = get("fill") {
                out.push((Kind::Fill, Val::F4(color4(v)?)));
            }
            if let Some(v) = get("fill-opacity") {
                out.push((Kind::FillOpacity, Val::F(fnum(v, "fill-opacity")?)));
            }
        }
        op::STROKE => {
            if let Some(v) = get("stroke") {
                out.push((Kind::Stroke, Val::F4(color4(v)?)));
            }
            if let Some(v) = get("stroke-opacity") {
                out.push((Kind::StrokeOpacity, Val::F(fnum(v, "stroke-opacity")?)));
            }
            if let Some(v) = get("stroke-width") {
                out.push((Kind::StrokeWidth, Val::F(fnum(v, "stroke-width")?)));
            }
        }
        op::GRADIENT => {
            if get("cx").is_some() {
                out.push((
                    Kind::Gradient,
                    Val::F4([
                        fnum(get("cx").unwrap_or("0"), "cx")?,
                        fnum(get("cy").unwrap_or("0"), "cy")?,
                        fnum(get("r").unwrap_or("0"), "r")?,
                        0.0,
                    ]),
                ));
            } else {
                out.push((
                    Kind::Gradient,
                    Val::F4([
                        fnum(get("x1").unwrap_or("0"), "x1")?,
                        fnum(get("y1").unwrap_or("0"), "y1")?,
                        fnum(get("x2").unwrap_or("0"), "x2")?,
                        fnum(get("y2").unwrap_or("0"), "y2")?,
                    ]),
                ));
            }
        }
        op::RAMP => {
            let o = fnum(get("offset").unwrap_or("0"), "offset")?;
            let c = color4(get("stop-color").unwrap_or("rgb(0,0,0)"))?;
            out.push((Kind::Stop, Val::F4([o, c[0], c[1], c[2]])));
        }
        op::DASH => {
            let array: Result<Vec<f32>> = get("stroke-dasharray")
                .unwrap_or("")
                .split(' ')
                .filter(|p| !p.is_empty())
                .map(|p| fnum(p, "stroke-dasharray"))
                .collect();
            out.push((
                Kind::Dash,
                Val::Dash(Dash {
                    array: array?,
                    offset: fnum(get("stroke-dashoffset").unwrap_or("0"), "stroke-dashoffset")?,
                }),
            ));
        }
        op::FX_BLUR => {
            if let Some(v) = get("stdDeviation") {
                let p: Vec<&str> = v.split(' ').collect();
                ensure!(
                    p.len() == 2,
                    "FX_BLUR stdDeviation `{v}` is not an x/y pair"
                );
                out.push((
                    Kind::BlurStd,
                    Val::F2([fnum(p[0], "stdDeviation")?, fnum(p[1], "stdDeviation")?]),
                ));
            }
        }
        op::FX_STD => {
            if let Some(v) = get("stdDeviation") {
                out.push((Kind::ShadowStd, Val::F(fnum(v, "stdDeviation")?)));
            }
        }
        op::FX_FLOOD_O => {
            if let Some(v) = get("flood-opacity") {
                out.push((Kind::FloodOpacity, Val::F(fnum(v, "flood-opacity")?)));
            }
        }
        op::FX_OFFSET => {
            out.push((
                Kind::ShadowOffset,
                Val::F2([
                    fnum(get("dx").unwrap_or("0"), "dx")?,
                    fnum(get("dy").unwrap_or("0"), "dy")?,
                ]),
            ));
        }
        other => bail!("the rt target cannot bake binding op {other}"),
    }
    Ok(out)
}

/// Dense integer-frame samples → change-point tracks. A gated-off frame
/// holds the previous value (the runtime would not have written); frames
/// before a channel's first live write emit no key (the static scene value
/// stands). Compression keeps an anchor key on the frame *before* each
/// change, so piecewise-linear interpolation between the kept keys
/// reproduces the dense bake exactly at every integer frame.
fn build_tracks(samples: &[SampleFrame], frames: &[f64]) -> Result<Vec<Track>> {
    let mut dense: BTreeMap<(u32, Kind), Vec<Option<Val>>> = BTreeMap::new();
    for (fi, frame) in samples.iter().enumerate() {
        for (el, opc, attrs) in frame {
            for (kind, val) in channel_writes(*opc, attrs)? {
                dense
                    .entry((*el, kind))
                    .or_insert_with(|| vec![None; samples.len()])[fi] = Some(val);
            }
        }
    }

    let mut per_slot: BTreeMap<u32, Vec<Channel>> = BTreeMap::new();
    for ((slot, kind), mut vals) in dense {
        // Gated-off frames hold.
        for i in 1..vals.len() {
            if vals[i].is_none() {
                vals[i] = vals[i - 1].clone();
            }
        }
        // Change points with pre-change anchors.
        let mut keys: Vec<(f32, Val)> = Vec::new();
        let mut last_kept: Option<usize> = None;
        for (i, v) in vals.iter().enumerate() {
            let Some(v) = v else { continue };
            let changed = match keys.last() {
                Some((_, prev)) => prev != v,
                None => true,
            };
            if changed {
                if let Some(lk) = last_kept
                    && lk != i - 1
                {
                    let anchor = vals[i - 1].clone().unwrap();
                    keys.push((frames[i - 1] as f32, anchor));
                }
                keys.push((frames[i] as f32, v.clone()));
                last_kept = Some(i);
            }
        }
        if keys.is_empty() {
            continue;
        }
        per_slot
            .entry(slot)
            .or_default()
            .push(channel_of(kind, keys));
    }

    Ok(per_slot
        .into_iter()
        .map(|(slot, channels)| Track { slot, channels })
        .collect())
}

fn channel_of(kind: Kind, keys: Vec<(f32, Val)>) -> Channel {
    let frames: Vec<f32> = keys.iter().map(|(f, _)| *f).collect();
    macro_rules! pull {
        ($variant:ident) => {
            Keys {
                frames,
                values: keys
                    .into_iter()
                    .map(|(_, v)| match v {
                        Val::$variant(x) => x,
                        other => unreachable!("kind/value mismatch: {other:?}"),
                    })
                    .collect(),
            }
        };
    }
    match kind {
        Kind::Matrix => Channel::Matrix(pull!(F6)),
        Kind::Opacity => Channel::Opacity(pull!(F)),
        Kind::Hidden => Channel::Hidden(pull!(F)),
        Kind::Path => Channel::Path(pull!(Path)),
        Kind::Rect => Channel::Rect(pull!(F6)),
        Kind::Ellipse => Channel::Ellipse(pull!(F4)),
        Kind::Fill => Channel::Fill(pull!(F4)),
        Kind::FillOpacity => Channel::FillOpacity(pull!(F)),
        Kind::Stroke => Channel::Stroke(pull!(F4)),
        Kind::StrokeOpacity => Channel::StrokeOpacity(pull!(F)),
        Kind::StrokeWidth => Channel::StrokeWidth(pull!(F)),
        Kind::Dash => Channel::Dash(pull!(Dash)),
        Kind::Gradient => Channel::Gradient(pull!(F4)),
        Kind::Stop => Channel::Stop(pull!(F4)),
        Kind::BlurStd => Channel::BlurStd(pull!(F2)),
        Kind::ShadowStd => Channel::ShadowStd(pull!(F)),
        Kind::FloodOpacity => Channel::FloodOpacity(pull!(F)),
        Kind::ShadowOffset => Channel::ShadowOffset(pull!(F2)),
    }
}

