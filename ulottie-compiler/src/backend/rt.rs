//! The `rt` target: the native tiny-skia rasterizer (`ulottie-rt`).
//!
//! Same display list as `skia-aot`, different consumer — instead of a JS
//! descriptor walked by a worklet, the restructured markup lowers to **RTDL**
//! (`ulottie_rt::rtdl`), a renderer-agnostic binary scene: numbers only, paths
//! as verb+point arrays, colours as float RGBA. The per-frame side flips from
//! runtime programs to compile-time baking: `scene::plan_sampled` runs the
//! binding bake at every integer frame, and the samples compress into numeric
//! keyframe tracks the native player interpolates. The emitted module carries
//! the blob as base64 plus a numeric `meta`; per-frame JS work on device is a
//! single `renderFrame(id, frame)` JSI call.
//!
//! The compiler links the very structs the device decodes (`ulottie-rt` with
//! `default-features = false`), and drives the same track `Player` for its
//! mandatory bbox pass: every group that forces an offscreen layer (opacity,
//! blend, mask, matte filter, effects) gets the union of its subtree's
//! animated bounds stamped on, because an unbounded native saveLayer measured
//! 13× slower.
//!
//! Refusals match `skia-aot` exactly (`support::scan_skia`, the same caps
//! whitelist, named bail on any unlowerable construct). One softer edge: a
//! scene whose node count is past the tiny-skia 60 fps budget compiles with a
//! named WARNING (stderr + module comment), not a refusal.

