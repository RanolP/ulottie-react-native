const DEF_TAGS: &[&str] = &[
    "defs",
    "clipPath",
    "mask",
    "linearGradient",
    "radialGradient",
    "filter",
];

fn index_defs<'a>(n: &'a Node, map: &mut BTreeMap<&'a str, &'a Node>) {
    if let Some((_, id)) = n.attrs.iter().find(|(k, _)| k == "id")
        && DEF_TAGS.contains(&n.tag.as_str())
    {
        map.insert(id, n);
    }
    for c in &n.children {
        index_defs(c, map);
    }
}

fn attr<'n>(n: &'n Node, key: &str) -> Option<&'n str> {
    n.attrs
        .iter()
        .find(|(k, _)| k == key)
        .map(|(_, v)| v.as_str())
}

struct Build<'a> {
    defs: &'a BTreeMap<&'a str, &'a Node>,
    bound: &'a BTreeSet<usize>,
    /// Every slot stamped on an emitted node — checked against `bound` so a
    /// binding into a defs subtree fails loudly, same as skia-aot.
    slots: BTreeSet<usize>,
    nodes: Vec<RtNode>,
    gradients: Vec<Gradient>,
    /// Gradient defs pooled by id: a def shared by two paints resolves to one
    /// pool entry, so a bound gradient has exactly one track target.
    grad_ids: BTreeMap<String, u32>,
    images: Vec<Image>,
}

impl<'a> Build<'a> {
    /// A node's slot: registered always, carried only when a track binds it.
    fn take_slot(&mut self, s: Option<usize>) -> Option<u32> {
        let s = s?;
        self.slots.insert(s);
        self.bound.contains(&s).then_some(s as u32)
    }

    fn lookup(&self, v: &str, what: &str) -> Result<&'a Node> {
        let id = v
            .strip_prefix("url(#")
            .and_then(|r| r.strip_suffix(')'))
            .ok_or_else(|| anyhow::anyhow!("unsupported {what} value `{v}`"))?;
        self.defs
            .get(id)
            .copied()
            .ok_or_else(|| anyhow::anyhow!("unresolved reference `{v}`"))
    }

    /// Drawable children (defs skipped) → arena indices.
    fn lower_list(&mut self, children: &[Node]) -> Result<Vec<u32>> {
        let mut out = Vec::new();
        for c in children {
            if DEF_TAGS.contains(&c.tag.as_str()) {
                continue;
            }
            out.push(self.lower_node(c)?);
        }
        Ok(out)
    }

    fn lower_node(&mut self, n: &Node) -> Result<u32> {
        let node = match n.tag.as_str() {
            "g" => RtNode::Group(self.lower_group(n)?),
            "path" | "rect" | "ellipse" => RtNode::Shape(self.lower_shape(n)?),
            "image" => RtNode::Image(self.lower_image(n)?),
            other => bail!("the rt target cannot lower <{other}>"),
        };
        self.nodes.push(node);
        Ok((self.nodes.len() - 1) as u32)
    }

    fn lower_group(&mut self, n: &Node) -> Result<Group> {
        let mut g = Group {
            slot: self.take_slot(n.slot),
            opacity: 1.0,
            ..Group::default()
        };
        for (k, v) in &n.attrs {
            match k.as_str() {
                "transform" => g.matrix = Some(transform6(v)?),
                "opacity" => g.opacity = fnum(v, "opacity")?,
                "display" if v == "none" => g.hidden = true,
                "style" => {
                    for decl in v.split(';').filter(|d| !d.is_empty()) {
                        match decl {
                            // The viewport clip already rides the flattened
                            // group's clip-path.
                            "overflow:hidden" => {}
                            "display:none" => g.hidden = true,
                            other => match other.strip_prefix("mix-blend-mode:") {
                                Some(kw) => g.blend = Some(blend_of(kw)?),
                                None => bail!("unsupported style `{other}` in the rt target"),
                            },
                        }
                    }
                }
                "clip-path" => g.clip = Some(self.lower_clip(v)?),
                "mask" => g.mask = Some(self.lower_mask(v)?),
                "filter" => self.lower_filter(v, &mut g)?,
                other => bail!("the rt target cannot lower <g {other}>"),
            }
        }
        g.children = self.lower_list(&n.children)?;
        Ok(g)
    }

    fn lower_clip(&mut self, v: &str) -> Result<Clip> {
        let def = self.lookup(v, "clip-path")?;
        ensure!(def.tag == "clipPath", "`{v}` does not name a <clipPath>");
        for (k, val) in &def.attrs {
            match k.as_str() {
                "id" => {}
                "clipPathUnits" if val == "userSpaceOnUse" => {}
                other => bail!("the rt target cannot lower <clipPath {other}>"),
            }
        }
        ensure!(
            def.children.len() == 1,
            "the rt target only lowers single-shape clip paths"
        );
        let c = &def.children[0];
        match c.tag.as_str() {
            "rect" => {
                let (mut x, mut y, mut w, mut h) = (0.0, 0.0, None, None);
                for (k, val) in &c.attrs {
                    match k.as_str() {
                        "x" => x = fnum(val, "x")?,
                        "y" => y = fnum(val, "y")?,
                        "width" => w = Some(fnum(val, "width")?),
                        "height" => h = Some(fnum(val, "height")?),
                        other => bail!("the rt target cannot lower a clip <rect {other}>"),
                    }
                }
                let (Some(w), Some(h)) = (w, h) else {
                    bail!("clip <rect> without width/height");
                };
                Ok(Clip::Rect([x, y, w, h]))
            }
            "path" => {
                let slot = self.take_slot(c.slot);
                let mut path = None;
                let mut eo = false;
                for (k, val) in &c.attrs {
                    match k.as_str() {
                        "d" => path = Some(parse_path(val)?),
                        "clip-rule" | "fill-rule" => eo = fill_rule_eo(val)?,
                        other => bail!("the rt target cannot lower a clip <path {other}>"),
                    }
                }
                // An animated-from-`ip` clip has no baked `d`: empty verbs
                // clip everything away until the first track key writes it.
                ensure!(path.is_some() || slot.is_some(), "clip <path> without d");
                Ok(Clip::Path {
                    slot,
                    path: path.unwrap_or_default(),
                    even_odd: eo,
                })
            }
            other => bail!("the rt target cannot lower a <{other}> clip shape"),
        }
    }

    fn lower_gradient(&mut self, v: &str) -> Result<u32> {
        let def = self.lookup(v, "paint")?;
        let radial = match def.tag.as_str() {
            "radialGradient" => true,
            "linearGradient" => false,
            other => bail!("`{v}` names a <{other}>, not a gradient"),
        };
        let id = attr(def, "id").unwrap_or("").to_string();
        if let Some(&gi) = self.grad_ids.get(&id) {
            return Ok(gi);
        }
        let slot = self.take_slot(def.slot);
        let bound_self = slot.is_some();
        let mut coords: BTreeMap<&str, f32> = BTreeMap::new();
        let mut gt = None;
        let mut units = false;
        for (k, val) in &def.attrs {
            match k.as_str() {
                "id" => {}
                "gradientUnits" if val == "userSpaceOnUse" => units = true,
                "gradientTransform" => gt = Some(transform6(val)?),
                "cx" | "cy" | "r" if radial => {
                    coords.insert(k, fnum(val, k)?);
                }
                "x1" | "y1" | "x2" | "y2" if !radial => {
                    coords.insert(k, fnum(val, k)?);
                }
                other => bail!("the rt target cannot lower <{} {other}>", def.tag),
            }
        }
        ensure!(
            units,
            "<{}> without gradientUnits=\"userSpaceOnUse\"",
            def.tag
        );
        let at = |k: &str| -> Result<f32> {
            match coords.get(k) {
                Some(v) => Ok(*v),
                // The Gradient track writes every coordinate at its first key.
                None if bound_self => Ok(0.0),
                None => bail!("<{}> without `{k}`", def.tag),
            }
        };
        let coords = if radial {
            [at("cx")?, at("cy")?, at("r")?, 0.0]
        } else {
            [at("x1")?, at("y1")?, at("x2")?, at("y2")?]
        };
        let mut stops = Vec::new();
        for s in &def.children {
            ensure!(s.tag == "stop", "unexpected <{}> inside a gradient", s.tag);
            let stop_slot = self.take_slot(s.slot);
            let (mut off, mut color) = (None, None);
            for (k, val) in &s.attrs {
                match k.as_str() {
                    "offset" => off = Some(fnum(val, "offset")?),
                    "stop-color" => color = Some(color4(val)?),
                    other => bail!("the rt target cannot lower <stop {other}>"),
                }
            }
            // A bound stop defaults until its first RAMP key writes it.
            let (off, color) = if stop_slot.is_some() {
                (off.unwrap_or(0.0), color.unwrap_or([0.0, 0.0, 0.0, 1.0]))
            } else {
                match (off, color) {
                    (Some(o), Some(c)) => (o, c),
                    _ => bail!("<stop> without offset/stop-color"),
                }
            };
            stops.push(Stop {
                slot: stop_slot,
                offset: off,
                color,
            });
        }
        self.gradients.push(Gradient {
            slot,
            radial,
            coords,
            stops,
            transform: gt,
        });
        let gi = (self.gradients.len() - 1) as u32;
        self.grad_ids.insert(id, gi);
        Ok(gi)
    }

    fn lower_mask(&mut self, v: &str) -> Result<Mask> {
        let def = self.lookup(v, "mask")?;
        ensure!(def.tag == "mask", "`{v}` does not name a <mask>");
        let mut luma = true;
        for (k, val) in &def.attrs {
            match (k.as_str(), val.as_str()) {
                ("id", _) => {}
                ("mask-type" | "maskType", "alpha") => luma = false,
                ("mask-type" | "maskType", "luminance") => luma = true,
                ("maskUnits", "userSpaceOnUse") => {}
                ("x", "0") | ("y", "0") => {}
                ("width" | "height", val) => {
                    fnum(val, k)?;
                }
                (other, val) => bail!("the rt target cannot lower <mask {other}=\"{val}\">"),
            }
        }
        let children = self.lower_list(&def.children)?;
        Ok(Mask { luma, children })
    }

    fn lower_filter(&mut self, v: &str, g: &mut Group) -> Result<()> {
        let def = self.lookup(v, "filter")?;
        ensure!(def.tag == "filter", "`{v}` does not name a <filter>");
        if let Some(s) = def.slot {
            self.slots.insert(s);
        }
        if attr(def, "filterUnits") == Some("userSpaceOnUse") {
            g.cf = Some(self.lower_invert(def)?);
            return Ok(());
        }
        g.fx = self.lower_fx(def)?;
        Ok(())
    }

    fn lower_invert(&mut self, def: &'a Node) -> Result<MatteInvert> {
        let mut r: BTreeMap<&str, f32> = BTreeMap::new();
        for (k, val) in &def.attrs {
            match k.as_str() {
                "id" => {}
                "filterUnits" if val == "userSpaceOnUse" => {}
                "x" | "y" | "width" | "height" => {
                    r.insert(k, fnum(val, k)?);
                }
                other => bail!("the rt target cannot lower <filter {other}>"),
            }
        }
        let at = |k: &str| -> Result<f32> {
            r.get(k)
                .copied()
                .ok_or_else(|| anyhow::anyhow!("<filter> without `{k}`"))
        };
        ensure!(
            def.children.len() == 1 && def.children[0].tag == "feColorMatrix",
            "the rt target only lowers a single <feColorMatrix> filter"
        );
        let (m, cif) = self.fe_matrix(&def.children[0])?;
        ensure!(
            cif.is_none(),
            "unexpected color-interpolation-filters on a matte inversion"
        );
        let (x, y) = (at("x")?, at("y")?);
        Ok(MatteInvert {
            matrix: m,
            rect: [x, y, x + at("width")?, y + at("height")?],
        })
    }

    /// The layer-effect primitive chains `scene::build::emit_effects` writes,
    /// as sequential fx stages — the same recognition as skia-aot, including
    /// its documented divergence: percentage filter regions are dropped, so a
    /// drop shadow escapes lottie-web's default `0%/100%` region instead of
    /// clipping to the element's own box. (The tint pair keeps its declared
    /// spaces — the rasterizer runs the luminance matrix in linearRGB.)
    fn lower_fx(&mut self, def: &'a Node) -> Result<Vec<FxStage>> {
        for (k, val) in &def.attrs {
            match k.as_str() {
                "id" => {}
                "x" | "y" | "width" | "height" if val.ends_with('%') => {}
                other => bail!("the rt target cannot lower <filter {other}>"),
            }
        }
        let c = &def.children;
        let mut stages = Vec::new();
        let mut i = 0;
        while i < c.len() {
            match c[i].tag.as_str() {
                "feColorMatrix" => {
                    let (m, cif) = self.fe_matrix(&c[i])?;
                    if cif.as_deref() == Some("linearRGB") {
                        // Tint: source, luma (t1), ramp∘luma (t2), merged.
                        ensure!(i + 2 < c.len(), "truncated tint chain in the rt target");
                        let (m2, cif2) = self.fe_matrix(&c[i + 1])?;
                        ensure!(
                            cif2.as_deref() == Some("sRGB"),
                            "tint ramp matrix without sRGB interpolation"
                        );
                        self.fe_merge(&c[i + 2], 3)?;
                        stages.push(FxStage {
                            passes: vec![
                                FxPass::Source,
                                FxPass::ColorMatrix(m),
                                FxPass::ColorMatrix2 {
                                    outer: m2,
                                    inner: m,
                                },
                            ],
                        });
                        i += 3;
                    } else {
                        ensure!(
                            cif.as_deref() == Some("sRGB"),
                            "effect colour matrix without sRGB interpolation"
                        );
                        stages.push(FxStage {
                            passes: vec![FxPass::ColorMatrix(m)],
                        });
                        i += 1;
                    }
                }
                "feGaussianBlur" if attr(&c[i], "in") == Some("SourceAlpha") => {
                    ensure!(
                        i + 4 < c.len(),
                        "truncated drop-shadow chain in the rt target"
                    );
                    let pass = self.fe_shadow(&c[i], &c[i + 1], &c[i + 2], &c[i + 3], &c[i + 4])?;
                    stages.push(FxStage { passes: vec![pass] });
                    i += 5;
                }
                "feGaussianBlur" => {
                    let pass = self.fe_blur(&c[i])?;
                    stages.push(FxStage { passes: vec![pass] });
                    i += 1;
                }
                other => bail!("the rt target cannot lower <{other}>"),
            }
        }
        ensure!(!stages.is_empty(), "<filter> with no primitives");
        Ok(stages)
    }

    fn fe_matrix(&mut self, fe: &'a Node) -> Result<([f32; 20], Option<String>)> {
        ensure!(
            fe.tag == "feColorMatrix",
            "expected <feColorMatrix>, found <{}>",
            fe.tag
        );
        if let Some(s) = fe.slot {
            self.slots.insert(s);
        }
        let mut values = None;
        let mut cif = None;
        for (k, val) in &fe.attrs {
            match k.as_str() {
                "type" if val == "matrix" => {}
                "color-interpolation-filters" => cif = Some(val.clone()),
                "values" => values = Some(val),
                "result" => {}
                other => bail!("the rt target cannot lower <feColorMatrix {other}>"),
            }
        }
        let Some(values) = values else {
            bail!("<feColorMatrix> without values")
        };
        let parts: Vec<&str> = values.split_ascii_whitespace().collect();
        ensure!(
            parts.len() == 20,
            "color matrix with {} values",
            parts.len()
        );
        let mut m = [0.0f32; 20];
        for (i, p) in parts.iter().enumerate() {
            m[i] = fnum(p, "values")?;
        }
        Ok((m, cif))
    }

    fn fe_merge(&mut self, fe: &'a Node, n: usize) -> Result<()> {
        ensure!(
            fe.tag == "feMerge",
            "expected <feMerge>, found <{}>",
            fe.tag
        );
        if let Some(s) = fe.slot {
            self.slots.insert(s);
        }
        ensure!(
            fe.children.len() == n,
            "<feMerge> with {} inputs where {n} were expected",
            fe.children.len()
        );
        for c in &fe.children {
            ensure!(
                c.tag == "feMergeNode",
                "unexpected <{}> in <feMerge>",
                c.tag
            );
            if let Some(s) = c.slot {
                self.slots.insert(s);
            }
        }
        Ok(())
    }

    fn fe_shadow(
        &mut self,
        blur: &'a Node,
        off: &'a Node,
        flood: &'a Node,
        comp: &'a Node,
        merge: &'a Node,
    ) -> Result<FxPass> {
        let blur_slot = self.take_slot(blur.slot);
        let mut std_dev = 0.0;
        for (k, val) in &blur.attrs {
            match k.as_str() {
                "in" | "result" => {}
                "stdDeviation" => std_dev = fnum(val, k)?,
                other => bail!("the rt target cannot lower <feGaussianBlur {other}>"),
            }
        }
        ensure!(
            off.tag == "feOffset",
            "expected <feOffset>, found <{}>",
            off.tag
        );
        let offset_slot = self.take_slot(off.slot);
        let (mut dx, mut dy) = (0.0, 0.0);
        for (k, val) in &off.attrs {
            match k.as_str() {
                "in" | "result" => {}
                "dx" => dx = fnum(val, k)?,
                "dy" => dy = fnum(val, k)?,
                other => bail!("the rt target cannot lower <feOffset {other}>"),
            }
        }
        ensure!(
            flood.tag == "feFlood",
            "expected <feFlood>, found <{}>",
            flood.tag
        );
        let flood_slot = self.take_slot(flood.slot);
        let mut color = None;
        let mut fo = 1.0;
        for (k, val) in &flood.attrs {
            match k.as_str() {
                "result" => {}
                "flood-color" => color = Some(color4(val)?),
                "flood-opacity" => fo = fnum(val, k)?,
                other => bail!("the rt target cannot lower <feFlood {other}>"),
            }
        }
        let Some(color) = color else {
            bail!("<feFlood> without flood-color")
        };
        ensure!(
            comp.tag == "feComposite",
            "expected <feComposite>, found <{}>",
            comp.tag
        );
        if let Some(s) = comp.slot {
            self.slots.insert(s);
        }
        for (k, val) in &comp.attrs {
            match k.as_str() {
                "in" | "in2" | "result" => {}
                "operator" if val == "in" => {}
                other => bail!("the rt target cannot lower <feComposite {other}>"),
            }
        }
        self.fe_merge(merge, 2)?;
        Ok(FxPass::Shadow {
            blur_slot,
            offset_slot,
            flood_slot,
            std_dev,
            dx,
            dy,
            color,
            flood_opacity: fo,
        })
    }

    fn fe_blur(&mut self, fe: &'a Node) -> Result<FxPass> {
        let slot = self.take_slot(fe.slot);
        let (mut sx, mut sy) = (0.0, 0.0);
        let mut wrap = None;
        for (k, val) in &fe.attrs {
            match k.as_str() {
                "result" => {}
                "stdDeviation" => {
                    let p: Vec<&str> = val.split(' ').collect();
                    ensure!(p.len() == 2, "stdDeviation `{val}` is not an x/y pair");
                    sx = fnum(p[0], k)?;
                    sy = fnum(p[1], k)?;
                }
                "edgeMode" => {
                    wrap = Some(match val.as_str() {
                        "wrap" => true,
                        "duplicate" => false,
                        other => bail!("unsupported edgeMode `{other}`"),
                    });
                }
                other => bail!("the rt target cannot lower <feGaussianBlur {other}>"),
            }
        }
        let Some(wrap) = wrap else {
            bail!("<feGaussianBlur> without edgeMode")
        };
        Ok(FxPass::Blur { slot, sx, sy, wrap })
    }

    fn lower_image(&mut self, n: &Node) -> Result<ImageRef> {
        ensure!(n.children.is_empty(), "unexpected children inside <image>");
        let (mut w, mut h, mut data) = (None, None, None);
        for (key, v) in &n.attrs {
            match key.as_str() {
                "width" => w = Some(fnum(v, "width")?),
                "height" => h = Some(fnum(v, "height")?),
                "preserveAspectRatio" => {
                    ensure!(
                        v == "xMidYMid slice",
                        "unsupported preserveAspectRatio `{v}` in the rt target"
                    );
                }
                "href" => {
                    let b64 = v
                        .strip_prefix("data:")
                        .and_then(|rest| rest.split_once(";base64,"))
                        .map(|(_, b)| b);
                    let Some(b64) = b64 else {
                        bail!("the rt target cannot draw a non-embedded image source")
                    };
                    data = Some(
                        base64::engine::general_purpose::STANDARD
                            .decode(b64)
                            .context("embedded image base64")?,
                    );
                }
                other => bail!("the rt target cannot lower <image {other}>"),
            }
        }
        let (Some(w), Some(h), Some(data)) = (w, h, data) else {
            bail!("<image> without width/height/href");
        };
        self.images.push(decode_png(&data)?);
        Ok(ImageRef {
            image: (self.images.len() - 1) as u32,
            w,
            h,
        })
    }

    fn lower_shape(&mut self, n: &Node) -> Result<Shape> {
        ensure!(
            n.children.is_empty(),
            "unexpected children inside <{}>",
            n.tag
        );
        let kind = n.tag.as_str();
        let mut s = Shape {
            slot: self.take_slot(n.slot),
            matrix: None,
            opacity: 1.0,
            hidden: false,
            geom: match kind {
                // A geometry attribute animated from frame `ip` is not baked
                // and SVG defaults are 0 — a zero-extent shape draws nothing
                // until the first track key, matching the web behaviour.
                "path" => Geom::Path(PathData::default()),
                "rect" => Geom::Rect {
                    x: 0.0,
                    y: 0.0,
                    w: 0.0,
                    h: 0.0,
                    rx: 0.0,
                    ry: 0.0,
                },
                _ => Geom::Ellipse {
                    cx: 0.0,
                    cy: 0.0,
                    rx: 0.0,
                    ry: 0.0,
                },
            },
            even_odd: false,
            paint: Paint::default(),
        };
        // SVG paints black when `fill` is absent; `fill="none"` clears it.
        s.paint.fill = Some(PaintSource::Color([0.0, 0.0, 0.0, 1.0]));
        for (key, v) in &n.attrs {
            match key.as_str() {
                "transform" => s.matrix = Some(transform6(v)?),
                "opacity" => s.opacity = fnum(v, "opacity")?,
                "display" if v == "none" => s.hidden = true,
                "style" => {
                    for decl in v.split(';').filter(|d| !d.is_empty()) {
                        match decl {
                            "display:none" => s.hidden = true,
                            other => bail!("unsupported style `{other}` in the rt target"),
                        }
                    }
                }
                "d" if kind == "path" => s.geom = Geom::Path(parse_path(v)?),
                "fill-rule" | "clip-rule" => s.even_odd = fill_rule_eo(v)?,
                "x" | "y" | "width" | "height" | "rx" | "ry" if kind == "rect" => {
                    let Geom::Rect { x, y, w, h, rx, ry } = &mut s.geom else {
                        unreachable!()
                    };
                    let f = fnum(v, key)?;
                    match key.as_str() {
                        "x" => *x = f,
                        "y" => *y = f,
                        "width" => *w = f,
                        "height" => *h = f,
                        "rx" => *rx = f,
                        _ => *ry = f,
                    }
                }
                "cx" | "cy" | "rx" | "ry" if kind == "ellipse" => {
                    let Geom::Ellipse { cx, cy, rx, ry } = &mut s.geom else {
                        unreachable!()
                    };
                    let f = fnum(v, key)?;
                    match key.as_str() {
                        "cx" => *cx = f,
                        "cy" => *cy = f,
                        "rx" => *rx = f,
                        _ => *ry = f,
                    }
                }
                "fill" => {
                    s.paint.fill = if v == "none" {
                        None
                    } else if v.starts_with("url(") {
                        Some(PaintSource::Gradient(self.lower_gradient(v)?))
                    } else {
                        Some(PaintSource::Color(color4(v)?))
                    };
                }
                "fill-opacity" => s.paint.fill_opacity = fnum(v, key)?,
                "stroke" => {
                    if v != "none" {
                        s.paint.stroke = Some(if v.starts_with("url(") {
                            PaintSource::Gradient(self.lower_gradient(v)?)
                        } else {
                            PaintSource::Color(color4(v)?)
                        });
                    }
                }
                "stroke-opacity" => s.paint.stroke_opacity = fnum(v, key)?,
                "stroke-width" => s.paint.stroke_width = fnum(v, key)?,
                "stroke-linecap" => {
                    s.paint.cap = match v.as_str() {
                        "butt" => 0,
                        "round" => 1,
                        "square" => 2,
                        other => bail!("unsupported stroke-linecap `{other}`"),
                    };
                }
                "stroke-linejoin" => {
                    s.paint.join = match v.as_str() {
                        "miter" => 0,
                        "round" => 1,
                        "bevel" => 2,
                        other => bail!("unsupported stroke-linejoin `{other}`"),
                    };
                }
                "stroke-miterlimit" => s.paint.miter_limit = fnum(v, key)?,
                "stroke-dasharray" => {
                    let nums: Result<Vec<f32>> =
                        v.split(' ').map(|p| fnum(p, "stroke-dasharray")).collect();
                    s.paint
                        .dash
                        .get_or_insert(Dash {
                            array: Vec::new(),
                            offset: 0.0,
                        })
                        .array = nums?;
                }
                "stroke-dashoffset" => {
                    s.paint
                        .dash
                        .get_or_insert(Dash {
                            array: Vec::new(),
                            offset: 0.0,
                        })
                        .offset = fnum(v, key)?;
                }
                "paint-order" => {
                    ensure!(v == "stroke", "unsupported paint-order `{v}`");
                    s.paint.stroke_first = true;
                }
                other => bail!("the rt target cannot lower <{} {other}>", n.tag),
            }
        }
        Ok(s)
    }
}

/// An embedded PNG → straight (unpremultiplied) RGBA8. The one format the
/// bodymovin exporters embed; anything else refuses by name.
fn decode_png(bytes: &[u8]) -> Result<Image> {
    ensure!(
        bytes.starts_with(&[0x89, b'P', b'N', b'G']),
        "the rt target only decodes embedded PNG images"
    );
    let mut decoder = png::Decoder::new(std::io::Cursor::new(bytes));
    decoder.set_transformations(
        png::Transformations::ALPHA | png::Transformations::EXPAND | png::Transformations::STRIP_16,
    );
    let mut reader = decoder.read_info().context("PNG header")?;
    let mut buf = vec![0u8; reader.output_buffer_size()];
    let info = reader.next_frame(&mut buf).context("PNG frame")?;
    buf.truncate(info.buffer_size());
    let rgba = match info.color_type {
        png::ColorType::Rgba => buf,
        png::ColorType::GrayscaleAlpha => buf
            .chunks_exact(2)
            .flat_map(|ga| [ga[0], ga[0], ga[0], ga[1]])
            .collect(),
        other => bail!("unexpected decoded PNG colour type {other:?}"),
    };
    Ok(Image {
        width: info.width,
        height: info.height,
        rgba,
    })
}

/// The restructured markup → the static RTDL scene plus the element count.
fn animation_from_markup(scene: &scene::Scene) -> Result<(Animation, usize)> {
    let mut root = rn::parse_markup(&scene.markup)?;
    ensure!(root.tag == "svg", "the document root is <{}>", root.tag);
    let mut count = 0usize;
    rn::assign_slots(&mut root, true, &mut count);
    rn::lower_invert_filters(&mut root)?;
    rn::flatten_nested_svgs(&mut root)?;

    // Root sanity: the rasterizer assumes the design space starts at the
    // origin (the fit transform and the viewport clips do too).
    for (k, v) in &root.attrs {
        match k.as_str() {
            "viewBox" => ensure!(
                v.starts_with("0 0 "),
                "viewBox `{v}` does not start at the origin"
            ),
            "width" | "height" => {}
            "preserveAspectRatio" => ensure!(
                v == "xMidYMid meet",
                "unsupported preserveAspectRatio `{v}` (the player fits xMidYMid meet)"
            ),
            "xmlns" => {}
            "style" => {
                for decl in v.split(';').filter(|d| !d.is_empty()) {
                    ensure!(decl == "overflow:hidden", "unsupported root style `{decl}`");
                }
            }
            other => bail!("the rt target cannot lower <svg {other}>"),
        }
    }

    // Design size: numeric width/height, else the viewBox extent.
    let view: Vec<&str> = attr(&root, "viewBox").unwrap_or("").split(' ').collect();
    let dim = |name: &str, vb: usize| -> f32 {
        attr(&root, name)
            .and_then(|v| v.parse::<f32>().ok())
            .or_else(|| view.get(vb).and_then(|v| v.parse().ok()))
            .unwrap_or(0.0)
    };

    let bound: BTreeSet<usize> = scene.data.b.iter().map(|b| b.el_index as usize).collect();
    let mut defs = BTreeMap::new();
    index_defs(&root, &mut defs);
    let mut build = Build {
        defs: &defs,
        bound: &bound,
        slots: BTreeSet::new(),
        nodes: vec![RtNode::Group(Group::default())], // reserve the root
        gradients: Vec::new(),
        grad_ids: BTreeMap::new(),
        images: Vec::new(),
    };
    let children = build.lower_list(&root.children)?;
    build.nodes[0] = RtNode::Group(Group {
        opacity: 1.0,
        children,
        ..Group::default()
    });
    for b in &bound {
        ensure!(
            build.slots.contains(b),
            "binding addresses element {b}, which is not a drawable node (defs subtree or past the tree)"
        );
    }
    Ok((
        Animation {
            width: dim("width", 2),
            height: dim("height", 3),
            fr: scene.data.fr as f32,
            ip: scene.data.ip as f32,
            op: scene.data.op as f32,
            nodes: build.nodes,
            gradients: build.gradients,
            images: build.images,
            tracks: Vec::new(),
        },
        count,
    ))
}

